#!/usr/bin/env node

/**
 * Generates `src/internal/backend-base.ts`: one abstract class per private backend interface whose
 * every member refuses with a named diagnostic.
 *
 * A backend that implements part of the boundary -- the first WebAssembly slice does -- would
 * otherwise need several hundred hand-written stubs that go stale the moment the interface grows.
 * Generating them from the interface itself means a new backend member appears in every partial
 * backend as a truthful refusal rather than as a compile error nobody notices until later.
 *
 * Run `node tools/backend/generate-backend-base.mjs --check` to fail when the checked-in file is
 * not what the current interfaces produce.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const SOURCE = path.join(ROOT, "src/internal/backend.ts");
const OUTPUT = path.join(ROOT, "src/internal/backend-base.ts");

/** Properties every backend must answer for itself rather than refuse. */
const ABSTRACT_PROPERTIES = new Set(["Kind", "IsAvailable", "AbiVersion", "Detail"]);

function parse() {
  return ts.createSourceFile(
    "backend.ts",
    fs.readFileSync(SOURCE, "utf8"),
    ts.ScriptTarget.ES2022,
    true,
  );
}

function generate() {
  const source = parse();
  const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed });
  const print = (node) => printer.printNode(ts.EmitHint.Unspecified, node, source);

  const exportedTypeNames = [];
  const interfaces = [];
  source.forEachChild((node) => {
    const isExported = node.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword);
    if (!isExported) return;
    if (ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) {
      exportedTypeNames.push(node.name.text);
    }
    if (ts.isInterfaceDeclaration(node) && /^Cna\w*Backend$/.test(node.name.text)) {
      interfaces.push(node);
    }
  });

  const typeImports = source.statements
    .filter((statement) => ts.isImportDeclaration(statement) && statement.importClause?.isTypeOnly)
    .map((statement) => print(statement).replace(/"\.\.\//g, '"../').trim());

  const lines = [
    "// Generated by tools/backend/generate-backend-base.mjs. Do not edit by hand.",
    "//",
    "// One abstract class per private backend interface, whose every member refuses with the member's",
    "// own name. A backend that implements part of the boundary extends the matching class and",
    "// overrides what it actually reaches, so an unimplemented route is a truthful refusal instead of",
    "// a silent gap, and a member added to an interface reaches every partial backend at once.",
    "",
    ...typeImports,
    `import type {\n${[...new Set(exportedTypeNames)].sort().map((name) => `  ${name},`).join("\n")}\n} from "./backend.js";`,
    "",
  ];

  for (const declaration of interfaces) {
    const name = declaration.name.text;
    lines.push(`/** Refusing base for {@link ${name}}. */`);
    lines.push(`export abstract class ${name}Base implements ${name} {`);
    lines.push("  /** Refuses one member of this boundary, naming it. */");
    lines.push("  protected abstract unsupported(member: string): never;");
    for (const member of declaration.members) {
      if (member.questionToken) continue;
      const memberName = member.name.getText(source);
      if (ts.isPropertySignature(member)) {
        const type = member.type ? print(member.type) : "unknown";
        if (ABSTRACT_PROPERTIES.has(memberName)) {
          lines.push(`  public abstract readonly ${memberName}: ${type};`);
        } else {
          lines.push(`  public get ${memberName}(): ${type} { return this.unsupported(${JSON.stringify(memberName)}); }`);
        }
        continue;
      }
      if (!ts.isMethodSignature(member)) {
        throw new Error(`unsupported member kind in ${name}: ${memberName}`);
      }
      const parameters = member.parameters.map((parameter, index) => {
        const parameterName = parameter.name.getText(source);
        const optional = parameter.questionToken ? "?" : "";
        const type = parameter.type ? print(parameter.type) : "unknown";
        const dots = parameter.dotDotDotToken ? "..." : "";
        return `${dots}_${parameterName}${optional}: ${type}`;
      });
      const returnType = member.type ? print(member.type) : "void";
      const generics = member.typeParameters
        ? `<${member.typeParameters.map((parameter) => print(parameter)).join(", ")}>`
        : "";
      const body = /^Promise</.test(returnType)
        ? `{ try { return this.unsupported(${JSON.stringify(memberName)}); } catch (error) { return Promise.reject(error) as ${returnType}; } }`
        : `{ return this.unsupported(${JSON.stringify(memberName)}); }`;
      const signature = `  public ${memberName}${generics}(${parameters.join(", ")}): ${returnType} ${body}`;
      lines.push(signature.length <= 110 ? signature : [
        `  public ${memberName}${generics}(`,
        ...parameters.map((parameter) => `    ${parameter},`),
        `  ): ${returnType} ${body}`,
      ].join("\n"));
    }
    lines.push("}");
    lines.push("");
  }
  return `${lines.join("\n")}`;
}

const check = process.argv.includes("--check");
const generated = generate();
if (check) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, "utf8") : "";
  if (current !== generated) {
    console.error("src/internal/backend-base.ts is stale; run node tools/backend/generate-backend-base.mjs");
    process.exitCode = 1;
  } else {
    process.stdout.write("BACKEND_BASE_UP_TO_DATE=1\n");
  }
} else {
  fs.writeFileSync(OUTPUT, generated);
  process.stdout.write(`wrote ${path.relative(ROOT, OUTPUT)}\n`);
}
